import colorsys, sys

def rgb(h): h=h.lstrip('#'); return tuple(int(h[i:i+2],16)/255 for i in (0,2,4))
def lum(h):
    def f(c): return c/12.92 if c<=0.03928 else ((c+0.055)/1.055)**2.4
    r,g,b=[f(c) for c in rgb(h)]; return .2126*r+.7152*g+.0722*b
def cr(a,b):
    la,lb=lum(a),lum(b); 
    if la<lb: la,lb=lb,la
    return (la+.05)/(lb+.05)
def hexs(r,g,b): return '#%02x%02x%02x'%tuple(round(max(0,min(1,c))*255) for c in (r,g,b))
def shift(h,d):
    r,g,b=rgb(h); hh,l,s=colorsys.rgb_to_hls(r,g,b); return hexs(*colorsys.hls_to_rgb(hh,max(0,min(1,l+d)),s))

