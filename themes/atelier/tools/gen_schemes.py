def finish(p,dark):
    p=dict(p)
    p['hover']=shift(p['accent'],+.10 if dark else -.09)
    # on-accent: best of near-black / white
    cand=['#ffffff','#14110f']; p['on']=max(cand,key=lambda c:cr(c,p['accent']))
    return p

def check(name,mode,p):
    bad=[]
    def need(a,b,t,lbl):
        v=cr(p[a],p[b])
        if v<t: bad.append('%s %s/%s %.2f<%.1f'%(lbl,a,b,v,t))
    need('text','bg',7,'text'); need('text','surface',7,'text')
    need('muted','bg',4.5,'muted'); need('muted','surface',4.5,'muted'); need('muted','s2',4.5,'muted')
    need('accent','bg',4.5,'accent'); need('accent','surface',4.5,'accent'); need('accent','s2',4.5,'accent')
    need('hover','bg',4.5,'hover'); need('hover','surface',4.5,'hover')
    need('on','accent',4.5,'on-accent'); need('on','hover',4.5,'on-hover')
    need('strong','bg',3,'strong'); need('strong','surface',3,'strong')
    return bad

def block(sel,p,dark):
    return ('%s {\n\t--bg:%s; --surface:%s; --surface-2:%s; --text:%s; --muted:%s;\n\t--border:%s; --border-strong:%s;\n'
            '\t--accent:%s; --accent-hover:%s; --on-accent:%s;\n\t--danger:%s; --ok:%s;\n}\n')%(
        sel,p['bg'],p['surface'],p['s2'],p['text'],p['muted'],p['border'],p['strong'],p['accent'],p['hover'],p['on'],
        '#f2877f' if dark else '#b3261e','#7fcf84' if dark else '#2e6b32')

